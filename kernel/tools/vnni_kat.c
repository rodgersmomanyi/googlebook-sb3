/*
 * vnni_kat: the VEX-vs-EVEX AVX-VNNI known-answer test for Googlebook SB3 kernel build #15 (WAVE3_PLAN.md 3.5).
 *
 * The target (SB3 / the throwaway VMware guest) is Ice Lake: it runs the EVEX AVX512_VNNI forms natively but
 * raises #UD on the VEX AVX-VNNI forms, which k15 emulates in the #UD handler. This program compares the
 * emulated VEX result against a native EVEX result and a scalar C reference for every form (register, [rsi],
 * [rsi+64]), checks the architectural side effects (MAXVL zeroing, full register preservation, the SSE/YMM init
 * state with a stale xsave buffer), the negative encodings (SIGILL), a 6-byte memory-form op ending at a page
 * end, memory operands faulted in from fresh and zram-swapped pages, a bad address, preemption + SIGALRM stress,
 * and the exact /sys/kernel/gb_vnni counter deltas.
 *
 * r2 (wave 3 review H1, H2, M1, M2, M3 and the zmm0-31 clobber): the memory operand buffer is 128 bytes and the
 * reference reads it at the op's displacement; the page-end case runs the 6-byte [rsi+64] op through a call
 * trampoline on a full register file; the init-state cases snapshot XINUSE inside the same asm blob as vzeroall/
 * vzeroupper and the op, and compare every register; --all includes the zram case (an absent case is a SKIP);
 * the counter deltas are compared exactly with the counts this program executed (forked workers report theirs
 * through shared memory).
 *
 * Every instruction under test is a block of explicit bytes assembled by GNU as (vnni_kat_ops.h, generated by
 * gen_vnni_kat_ops.py) copied into an executable page, so neither the compiler nor the assembler can re-encode
 * or interleave it; gen_vnni_kat_check.py disassembles every op and re-asserts its encoding.
 * Workers are fork()ed, never threads.
 *
 * Builds (build_vnni_kat.sh):
 *   target      <ndk>/clang --target=x86_64-linux-android34 -static -O2 -I<ops dir> -o vnni_kat vnni_kat.c
 *   host check  cc -O2 -DGB_VNNI_HOSTCHECK ...: a builder with AVX512_VNNI runs every case on the native EVEX forms
 *               against the scalar reference, so the harness itself is validated (no emulation there).
 *   user emu    cc -O2 -DGB_VNNI_USEREMU -I<dir of gb_vnni_core.h> ...: host-only test build, never shipped. A
 *               SIGILL handler emulates the VEX ops with the k15 emulator core (gb_vnni_core.h, the same file
 *               traps.c includes) on the signal frame's XSAVE image, the memory operand read through a kernel
 *               copy_from_user (a pipe write), and keeps the counters in shared memory: the whole target logic
 *               incl. the exact counter deltas runs on the builder. -DGB_VNNI_USEREMU_K14 uses the k14 merge
 *               (k14_merge_ref.h, negative control): it must FAIL.
 * Run (target): vnni_kat --all   (gb_vnni_kat.sh, after swapon /dev/block/zram0; --zram is the same flag). Without
 * it the zram case is reported as "SKIP zram". Output: "GB_VNNI_KAT: PASS <n> cases (<s> skipped: <names>)" or
 * "GB_VNNI_KAT: FAIL case=<first failure> (pass=.. fail=.. skip=..)"; exit 0 / 1, 2 = environment (ENV line).
 *
 * Counter tolerance: the counters are system-wide. The deltas must equal this program's counts exactly. If a delta
 * is larger and the summary's comm/RIP list shows another process emulating meanwhile, the counted battery is
 * re-run up to 3 times and must be exact once with no other process active ("exact on quiet re-run <n>");
 * otherwise FAIL case=counter_foreign. A smaller delta, or irqon != emulated, always fails.
 *
 * Our own code (no gbos-x86). Premise (Ice Lake has AVX512_VNNI, not AVX_VNNI) confirmed on the SB3 and the builder.
 */
