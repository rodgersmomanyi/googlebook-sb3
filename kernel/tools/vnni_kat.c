static void skipc(const char *name)
{
	size_t nl = strlen(name);
	int i;

	g_skip++;
	for (char *p = g_skips; (p = strstr(p, name)); p += 1)
		if ((p == g_skips || p[-1] == ',') && (p[nl] == 0 || p[nl] == ','))
			return;				/* already listed */
	i = (int)strlen(g_skips);
	snprintf(g_skips + i, sizeof(g_skips) - i, "%s%s", i ? "," : "", name);
}
