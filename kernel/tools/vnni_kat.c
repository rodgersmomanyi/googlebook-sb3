static struct ue_counts *g_ue;		/* MAP_SHARED: forked workers count into it too */
static u32 g_ue_yoff, g_ue_zoff;
static int g_ue_pipe[2] = { -1, -1 };
static pid_t g_ue_pipe_pid;
static const int ue_greg[16] = { REG_RAX, REG_RCX, REG_RDX, REG_RBX, REG_RSP, REG_RBP, REG_RSI, REG_RDI,
				 REG_R8, REG_R9, REG_R10, REG_R11, REG_R12, REG_R13, REG_R14, REG_R15 };
static void ue_add(u64 *p) { __atomic_fetch_add(p, 1, __ATOMIC_RELAXED); }
/* the instruction bytes up to the first unreadable one, like insn_fetch_from_user() */
static int ue_fetch(u8 *ib, u64 ip)
{
	struct iovec l = { ib, 15 }, r[15];
	ssize_t n;
	int i;

	for (i = 0; i < 15; i++) {
		r[i].iov_base = (void *)(uintptr_t)(ip + (u64)i);
		r[i].iov_len = 1;
	}
	n = process_vm_readv(getpid(), &l, 1, r, 15, 0);
	return n < 0 ? 0 : (int)n;
}
/* the memory operand through a kernel copy_from_user (a pipe write): a fresh page is faulted in from kernel mode
 * and counted in ru_minflt, a bad address gives EFAULT -- as the k15 emulator's copy_from_user */
static int ue_copy(void *dst, u64 src, size_t n)
{
	pid_t me = getpid();
	char drain[64];

	if (g_ue_pipe_pid != me) {
		if (pipe2(g_ue_pipe, O_NONBLOCK | O_CLOEXEC))
			return -1;
		g_ue_pipe_pid = me;
	}
	if (write(g_ue_pipe[1], (const void *)(uintptr_t)src, n) != (ssize_t)n) {
		while (read(g_ue_pipe[0], drain, sizeof(drain)) > 0)
			;
		return -1;
	}
	return read(g_ue_pipe[0], dst, n) == (ssize_t)n ? 0 : -1;
}
static int ue_emulate(ucontext_t *uc)
{
	greg_t *g = uc->uc_mcontext.gregs;
	u8 *fp = (u8 *)uc->uc_mcontext.fpregs;
	u64 rip = (u64)g[REG_RIP], xfs, *xf;
	struct gb_vnni_insn in;
	unsigned int fl;
	u32 magic, xsz, mem[8];
	u8 ib[15], *ymm, *zhi;
	int n;

	if (!fp)
		return 0;
	memcpy(&magic, fp + 464, 4);			/* struct _fpx_sw_bytes at 464: an XSAVE frame */
	memcpy(&xfs, fp + 472, 8);
	memcpy(&xsz, fp + 480, 4);
	if (magic != 0x46505853u || (xfs & (GB_VNNI_XF_YMM | GB_VNNI_XF_ZMM_HI256)) !=
	    (GB_VNNI_XF_YMM | GB_VNNI_XF_ZMM_HI256) || xsz < g_ue_zoff + 512)
		return 0;
	n = ue_fetch(ib, rip);
	switch (gb_vnni_decode(ib, n, &in)) {
	case GB_VNNI_OK:
		break;
	case GB_VNNI_SHORT:
		ue_add(&g_ue->efault);
		return 0;
	default:
		return 0;
	}
	memset(mem, 0, sizeof(mem));
	if (in.src2 < 0) {
		u64 ea = gb_vnni_ea(&in, in.base >= 0 ? (u64)g[ue_greg[(int)in.base]] : 0,
				    in.index >= 0 ? (u64)g[ue_greg[(int)in.index]] : 0, rip + in.len);

		if (ue_copy(mem, ea, in.l ? 32 : 16)) {
			ue_add(&g_ue->efault);
			return 0;
		}
	}
	xf = (u64 *)(void *)(fp + 512);			/* the XSAVE header: XSTATE_BV */
	ymm = (*xf & GB_VNNI_XF_YMM) ? fp + g_ue_yoff : NULL;
	zhi = (*xf & GB_VNNI_XF_ZMM_HI256) ? fp + g_ue_zoff : NULL;
	fl = UE_MERGE(&in, mem, (u32 *)(void *)(fp + 160), xf, ymm, zhi);
	g[REG_RIP] = (greg_t)(rip + in.len);
	ue_add(&g_ue->emulated);
	ue_add(in.l ? &g_ue->vex256 : &g_ue->vex128);
	ue_add(in.op >= 0x52 ? &g_ue->word : &g_ue->byte);
	ue_add(&g_ue->irqon);
	if (fl & GB_VNNI_F_SSE_INIT) ue_add(&g_ue->sse_init);
	if (fl & GB_VNNI_F_YMM_INIT) ue_add(&g_ue->ymm_init);
	if (fl & GB_VNNI_F_ZMMHI) ue_add(&g_ue->zmmhi);
	return 1;
}
static int ue_init(void)
{
	u32 a, b, c, d;

	g_ue = mmap(NULL, sizeof(*g_ue), PROT_READ | PROT_WRITE, MAP_SHARED | MAP_ANONYMOUS, -1, 0);
	if (g_ue == MAP_FAILED)
		return 0;
	memset(g_ue, 0, sizeof(*g_ue));
	if (!__get_cpuid_count(0x0d, 2, &a, &b, &c, &d))
		return 0;
	g_ue_yoff = b;
	__get_cpuid_count(0x0d, 6, &a, &b, &c, &d);
	g_ue_zoff = b;
	return g_ue_yoff && g_ue_zoff;
}
