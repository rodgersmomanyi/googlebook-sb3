"""KAT-0 decode vectors from the assembler (independent oracle for gb_vnni_decode()).

Writes AT&T source for every VEX AVX-VNNI form the emulator must decode -- every opcode x VEX.128/256, register
sources over r0-15, and memory sources [base], [base+disp8], [base+disp32], [base+index*scale(+disp)],
[index*scale+disp32], [disp32] and RIP-relative over every GPR (incl. rsp/r12 as base, r12 as index, rbp/r13 as
base) -- plus foreign encodings (EVEX, AVX-VNNI-INT8) that must be refused. Assembles with GNU as, reads the bytes
back with objdump and writes one line per instruction:
  OK  <hex> <op> <l> <dst> <src1> <src2|-1> <len> <base> <index> <scale> <rip> <disp>
  NOT <hex>
Usage: python3 -I gen_decode_vectors.py <out-vectors> <workdir>
"""
import os
import re
import subprocess
import sys

GPR = ["rax", "rcx", "rdx", "rbx", "rsp", "rbp", "rsi", "rdi", "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15"]
OPS = {0x50: "vpdpbusd", 0x51: "vpdpbusds", 0x52: "vpdpwssd", 0x53: "vpdpwssds"}


def main(out, work):
    os.makedirs(work, exist_ok=True)
    items = []          # (asm, expected tuple or None for NOT)
    for op, mn in OPS.items():
        for l in (0, 1):
            v = "%ymm" if l else "%xmm"
            # register forms: a spread over 0-15 for each field
            for dst, s1, s2 in [(0, 0, 0), (1, 2, 3), (7, 8, 9), (8, 15, 0), (15, 7, 8), (9, 9, 15), (3, 12, 13),
                                (12, 4, 11), (14, 13, 1), (5, 10, 6)]:
                items.append(("{vex} %s %s%d, %s%d, %s%d" % (mn, v, s2, v, s1, v, dst),
                              (op, l, dst, s1, s2, -1, -1, 0, 0, 0)))
            d, s1 = (op - 0x50) * 3 + l, (op - 0x50 + 5 + l) % 16
            for b in range(16):
                for disp in (None, 0x7f, -0x80, 0x12345678, -0x1000):
                    ds = "" if disp is None else ("%d" % disp)
                    items.append(("{vex} %s %s(%%%s), %s%d, %s%d" % (mn, ds, GPR[b], v, s1, v, d),
                                  (op, l, d, s1, -1, b, -1, 0, 0 if disp is None else disp, 0)))
                for x in range(16):
                    if x == 4:
                        continue            # rsp cannot be an index
                    for sc in (1, 2, 4, 8):
                        if (b + x + sc) % 3:   # keep the file small but every (base, index) and scale occurs
                            continue
                        disp = (0, 0x10, -0x7ffffff0)[(b * 16 + x) % 3]
                        items.append(("{vex} %s %d(%%%s,%%%s,%d), %s%d, %s%d" % (mn, disp, GPR[b], GPR[x], sc, v, s1, v,
                                                                              d),
                                      (op, l, d, s1, -1, b, x, sc.bit_length() - 1, disp, 0)))
            for x in range(16):
                if x == 4:
                    continue
                items.append(("{vex} %s 0x100(,%%%s,4), %s%d, %s%d" % (mn, GPR[x], v, s1, v, d),
                              (op, l, d, s1, -1, -1, x, 2, 0x100, 0)))
            items.append(("{vex} %s 0x12345, %s%d, %s%d" % (mn, v, s1, v, d), (op, l, d, s1, -1, -1, -1, 0, 0x12345, 0)))
            for disp in (0, 0x40, -0x40, 0x7fff0000):
                items.append(("{vex} %s %d(%%rip), %s%d, %s%d" % (mn, disp, v, s1, v, d),
                              (op, l, d, s1, -1, -1, -1, 0, disp, 1)))
            # foreign encodings that must never be emulated
            items.append(("{evex} %s %s1, %s2, %s3" % (mn, v, v, v), None))
            items.append(("{evex} %s 0x40(%%rax), %s2, %s3" % (mn, v, v), None))
    for mn in ("vpdpbssd", "vpdpbsud", "vpdpbuud", "vpdpbssds", "vpdpbsuds", "vpdpbuuds"):   # AVX-VNNI-INT8
        items.append(("%s %%xmm1, %%xmm2, %%xmm3" % mn, None))
        items.append(("%s (%%rax), %%ymm2, %%ymm3" % mn, None))

    src = os.path.join(work, "vec.s")
    obj = os.path.join(work, "vec.o")
    with open(src, "w") as f:
        f.write(".text\n")
        for i, (a, _) in enumerate(items):
            f.write("v%d: %s\n" % (i, a))
        f.write("vend: nop\n")
    subprocess.run(["as", "--64", "-o", obj, src], check=True)
    dis = subprocess.run(["objdump", "-d", "-w", "--no-show-raw-insn", "-t", obj], check=True, capture_output=True,
                         text=True).stdout
    addr = {}
    for m in re.finditer(r"^([0-9a-f]{16}) l\s+\.text\s+[0-9a-f]+ (v\d+|vend)$", dis, re.M):
        addr[m.group(2)] = int(m.group(1), 16)
    code = subprocess.run(["objcopy", "-O", "binary", "-j", ".text", obj, "/dev/stdout"], check=True,
                          capture_output=True).stdout
    names = ["v%d" % i for i in range(len(items))] + ["vend"]
    nok = nnot = 0
    with open(out, "w") as f:
        f.write("# generated by gen_decode_vectors.py from GNU as output (%d instructions)\n" % len(items))
        for i, (a, exp) in enumerate(items):
            b = code[addr[names[i]]:addr[names[i + 1]]]
            hx = b.hex()
            if exp is None:
                f.write("NOT %s  # %s\n" % (hx, a))
                nnot += 1
                continue
            op, l, dst, s1, s2, base, index, scale, disp, rip = exp
            f.write("OK %s %x %d %d %d %d %d %d %d %d %d %d  # %s\n"
                    % (hx, op, l, dst, s1, s2, len(b), base, index, scale, rip, disp, a))
            nok += 1
    print("vectors: %d OK, %d NOT -> %s" % (nok, nnot, out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
