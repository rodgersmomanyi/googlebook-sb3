#!/bin/bash
# k14 acceptance (INTERFACES 18.3 K-01..K-09, without hardware). Builder, after kbuild14_native.sh finished.
# Evidence: /build/k14/accept/K-xx.txt; summary on stdout and in /build/k14/accept/summary.txt.
# Usage: bash /build/k14/tools/k14_accept.sh        (reads /build/dist, /build/dist14, /build/k14/lapis)
set -u
K13=/build/dist
K14=/build/dist14
A=/build/k14/accept
T=/build/k14/tools
L=/build/k14/lapis
SRC=/build/gki/common
PY="nice -n 19 python3 -I"
mkdir -p "$A"
: > "$A/summary.txt"
res() { printf '%-5s %s  %s\n' "$1" "$2" "$3" | tee -a "$A/summary.txt"; }

[ -f /build/kbuild14.done ] || { echo "kbuild14 not done (/build/kbuild14.done missing)"; exit 1; }

# K-01: every commit on k14-nouveau (relative to k13-native) touches only drivers/gpu/drm/nouveau/
{
  n=0; bad=0
  for c in $(git -C "$SRC" rev-list --reverse k13-native..k14-nouveau); do
    n=$((n+1))
    files=$(git -C "$SRC" show --format= --name-only "$c")
    out=$(printf '%s\n' "$files" | grep -v '^drivers/gpu/drm/nouveau/' || true)
    printf '%s %s [%s files]%s\n' "$(git -C "$SRC" log -1 --format='%h %s' "$c")" "" "$(printf '%s\n' "$files" | grep -c .)" \
      "${out:+  OUTSIDE: $out}"
    [ -n "$out" ] && bad=$((bad+1))
  done
  echo "commits: $n, touching files outside drivers/gpu/drm/nouveau/: $bad"
  git -C "$SRC" diff --stat k13-native k14-nouveau | tail -1
} > "$A/K-01.txt" 2>&1
if grep -q "outside drivers/gpu/drm/nouveau/: 0$" "$A/K-01.txt" && grep -q "^commits: 40," "$A/K-01.txt"; then
  res K-01 PASS "$(tail -2 "$A/K-01.txt" | tr '\n' ' ')"; else res K-01 FAIL "see $A/K-01.txt"; fi

# K-02: .config identical
if diff "$K13/kernel_x86_64_dot_config" "$K14/kernel_x86_64_dot_config" > "$A/K-02.txt" 2>&1; then
  res K-02 PASS "kernel_x86_64_dot_config: empty diff ($(sha256sum < "$K14/kernel_x86_64_dot_config" | cut -c1-16))"
else res K-02 FAIL "$(wc -l < "$A/K-02.txt") diff lines"; fi

# K-03: vmlinux.symvers identical (+ informational: all module exports)
if diff "$K13/vmlinux.symvers" "$K14/vmlinux.symvers" > "$A/K-03.txt" 2>&1; then
  res K-03 PASS "vmlinux.symvers: empty diff ($(wc -l < "$K14/vmlinux.symvers") exports, sha256 $(sha256sum < "$K14/vmlinux.symvers" | cut -c1-16))"
else res K-03 FAIL "$(grep -c '^[<>]' "$A/K-03.txt") changed lines"; fi
diff "$K13/kernel_x86_64_Module.symvers" "$K14/kernel_x86_64_Module.symvers" > "$A/K-03-modules.txt" 2>&1
echo "kernel_x86_64_Module.symvers (vmlinux + all GKI module exports): $(grep -c '^[<>]' "$A/K-03-modules.txt") changed lines" >> "$A/K-03.txt"
res info "-" "kernel_x86_64_Module.symvers: $(grep -c '^[<>]' "$A/K-03-modules.txt") changed lines (all exports incl. modules)"

# K-04: modpost-style unresolved for the nouveau set (stage_kernel NATIVE_OPTIN) and its depends closure
$PY "$T/k14check.py" unresolved "$K14" nouveau drm_exec drm_gpuvm gpu-sched drm_ttm_helper > "$A/K-04.txt" 2>&1
rc=$?
if [ $rc = 0 ]; then res K-04 PASS "$(tail -1 "$A/K-04.txt")"; else res K-04 FAIL "$(tail -1 "$A/K-04.txt")"; fi

# K-05: every dist14 module signed by the bzImage's built-in key; then the staged set by name. Informational: whether
# k13 and k14 share the autogenerated signing key (the shared --config=local cache keeps certs/signing_key.pem)
$PY "$T/k14check.py" sig "$K14" > "$A/K-05.txt" 2>&1
rc=$?
STAGED="drm_sysfb_helper efidrm drm_ttm_helper vmwgfx psmouse vmxnet3 ac battery test_power libarc4 pps_core ptp rfkill
bluetooth btbcm hidp rfcomm zsmalloc zram mii usbnet cdc_ether cdc_ncm r8152 ax88179_178a cdc-acm crc-itu-t
surface_aggregator surface_aggregator_registry surface_aggregator_hub surface_aggregator_cdev surface_hid_core
surface_hid hid-surface surface_battery surface_charger surface_dtx surface_gpe surface_hotplug soc_button_array wmi
wmi-bmof video i2c-algo-bit drm_buddy drm_display_helper intel-gtt i915 kfifo_buf industrialio-triggered-buffer
apds9960 thermal ipts v4l2-cci ipu-bridge intel_skl_int3472_common intel_skl_int3472_discrete ov5693 ov8865 ov7251
dw9719 intel-ipu6 intel-ipu6-isys drm_exec drm_gpuvm gpu-sched nouveau surface_platform_profile hid-sensor-hub
hid-sensor-iio-common hid-sensor-trigger hid-sensor-accel-3d hid-sensor-gyro-3d hid-sensor-als hid-sensor-rotation
hid-sensor-incl-3d hid-sensor-magn-3d"
missing=""; files=""
for m in $STAGED; do
  f=$K14/$m.ko; [ -f "$f" ] || f=$K14/$(echo "$m" | tr - _).ko
  if [ -f "$f" ]; then files="$files $f"; else missing="$missing $m"; fi
done
# shellcheck disable=SC2086
$PY "$T/k14check.py" sig "$K14" $files > "$A/K-05-staged.txt" 2>&1
rc2=$?
echo "staged-set names not found in dist14:${missing:- none}" >> "$A/K-05-staged.txt"
$PY "$T/k14check.py" sig "$K13" "$K13/nouveau.ko" > "$A/K-05-k13-key.txt" 2>&1
fp13=$(grep -o 'sha256 Fingerprint=[0-9A-F:]*' "$A/K-05-k13-key.txt")
fp14=$(grep -o 'sha256 Fingerprint=[0-9A-F:]*' "$A/K-05.txt")
if [ $rc = 0 ] && [ $rc2 = 0 ] && [ -z "$missing" ]; then
  res K-05 PASS "$(tail -1 "$A/K-05.txt"); staged set: $(tail -2 "$A/K-05-staged.txt" | head -1 | cut -d, -f1-2)"
else res K-05 FAIL "rc=$rc staged rc=$rc2 missing=[$missing]"; fi
if [ "$fp13" = "$fp14" ]; then keyinfo="k13 and k14 use the SAME signing key ($fp14)"; else keyinfo="k13 and k14 signing keys differ"; fi
echo "$keyinfo" >> "$A/K-05.txt"
res info "-" "$keyinfo"

# K-06: lapis vendor_ramdisk (boot/vendor_ramdisk.lz4) + vendor_dlkm (276.R4 slot b, 271.R1 slot a) CRCs vs k14
ok6=1
for set in vr/a2/lib/modules vdlkm_b276 vdlkm_a; do
  tag=$(echo "$set" | tr / _)
  (cd "$L" && $PY "$T/k14check.py" crc "$K14" "$set") > "$A/K-06-$tag.txt" 2>&1 || ok6=0
  (cd "$L" && $PY "$T/k14check.py" crc "$K13" "$set") > "$A/K-06-$tag.k13.txt" 2>&1
  if cmp -s "$A/K-06-$tag.txt" "$A/K-06-$tag.k13.txt"; then same=identical; else same=DIFFERENT; ok6=0; fi
  res "   " "$set" "$(tail -1 "$A/K-06-$tag.txt") [k13 result: $same]"
done
if [ $ok6 = 1 ]; then res K-06 PASS "0 vmlinux CRC mismatches, 0 unresolved, same as k13"; else res K-06 FAIL "see $A/K-06-*.txt"; fi

# K-08: kernel release
{
  kr=$(cat "$K14/kernel_release.txt")
  k13r=$(sed -n 's/^kernel_release=//p' "$K13/gki-info.txt")
  tmp=$(mktemp /build/k14/vmlinux.XXXXXX)
  sh "$SRC/scripts/extract-vmlinux" "$K14/bzImage" > "$tmp" 2>/dev/null
  banner=$(grep -a -o -m1 'Linux version [^ ]*' "$tmp" | head -1 | cut -d' ' -f3)
  rm -f "$tmp"
  vm=$(/sbin/modinfo -F vermagic "$K14/nouveau.ko" | cut -d' ' -f1)
  echo "kernel_release.txt: $kr"
  echo "gki-info:           $(sed -n 's/^kernel_release=//p' "$K14/gki-info.txt")"
  echo "bzImage banner:     $banner"
  echo "nouveau vermagic:   $vm"
  echo "k13 release:        $k13r"
  echo "trailing whitespace in kernel_release.txt: $(grep -c '[[:space:]]$' "$K14/kernel_release.txt")"
  [ "$kr" = "$banner" ] && [ "$kr" = "$vm" ] && [ "$kr" != "$k13r" ] && [ "$(wc -l < "$K14/kernel_release.txt")" = 1 ] && echo RESULT=ok
} > "$A/K-08.txt" 2>&1
if grep -q RESULT=ok "$A/K-08.txt"; then res K-08 PASS "$(head -1 "$A/K-08.txt")"; else res K-08 FAIL "see $A/K-08.txt"; fi

# K-09: k13 working tree restored (kbuild14 --restore only verifies when HEAD is already back)
bash /build/k14/kbuild14_native.sh --restore > "$A/K-09.txt" 2>&1
{ echo "HEAD: $(git -C "$SRC" rev-parse HEAD) ($(git -C "$SRC" symbolic-ref -q HEAD || echo detached))"
  echo "branches: $(git -C "$SRC" for-each-ref --format='%(refname:short)=%(objectname:short=12)' refs/heads/ | tr '\n' ' ')"; } >> "$A/K-09.txt"
if grep -q "identical to saved state" "$A/K-09.txt"; then res K-09 PASS "$(grep 'identical' "$A/K-09.txt")"; else res K-09 FAIL "see $A/K-09.txt"; fi

# extra evidence: module set, patched strings, nouveau modinfo k13 vs k14
{
  kos() { find "$1" -maxdepth 1 -name '*.ko' -printf '%f\n' | sort; }
  diff <(kos "$K13") <(kos "$K14") && echo "module file set: identical ($(kos "$K14" | wc -l) .ko)"
  for s in "runtime PM through ACPI _PR3, hotplug left enabled" "GPU is no longer present on the bus" \
           "runtime suspend failed (%d), staying in D0" "failed to evict VRAM: %d"; do
    printf '%-48s k13=%s k14=%s\n' "\"$s\"" "$(grep -c -a -F "$s" "$K13/nouveau.ko")" "$(grep -c -a -F "$s" "$K14/nouveau.ko")"
  done
  for f in depends firmware parm; do
    if diff <(/sbin/modinfo -F $f "$K13/nouveau.ko") <(/sbin/modinfo -F $f "$K14/nouveau.ko") > /dev/null; then
      echo "nouveau modinfo $f: identical"; else echo "nouveau modinfo $f: DIFFERENT"; fi
  done
  sha256sum "$K14/bzImage" "$K14/nouveau.ko" "$K14/drm_exec.ko" "$K14/drm_gpuvm.ko" "$K14/gpu-sched.ko" "$K14/drm_ttm_helper.ko" \
    "$K14/vmlinux.symvers" "$K14/kernel_x86_64_dot_config"
} > "$A/extra.txt" 2>&1
res info "-" "$(grep -cE 'k13=0 k14=[1-9]' "$A/extra.txt")/4 new N1-N3 strings only in k14 nouveau.ko; $(grep -c identical "$A/extra.txt") identical checks (see extra.txt)"
grep -q FAIL "$A/summary.txt" && exit 1
exit 0
