# Generate the k15 patch set and the rewritten repository patches from the generators, without touching the
# builder's kernel tree (/build/gki/common is only read with `git show`).
#   patches/k15/0110-x86-traps-vnni-emulator-irq-ymm-xsave-counter.patch   k14 (v3 emulator) -> v4    (git am)
#   patches/k15/0111-i915-optional-ignore-user-gamma.patch               pristine i915 -> gb param   (git am)
#   repo/0002-x86-traps-emulate-VEX-AVX-VNNI-for-the-Googlebook-userspace.patch  pristine -> v4    (git apply)
#   repo/0005-i915-optional-ignore-user-gamma.patch                      pristine -> gb param       (git apply)
# A scratch repository holds P (3938c8d97142 files) -> B (k14-nouveau files) -> 0110 -> 0111; the commit ids
# are reproducible (fixed identity and dates).
# Usage (builder): bash gen_k15_patches.sh <tools dir with apply_vnni4.py + apply_i915_gamma.py> <out dir>
set -eu
T=${1:?tools dir}; OUT=${2:?out dir}
SRC=${KB15_GEN_SRC:-/build/gki/common}
BASE=3938c8d97142d5cf31543aa96f864a2cf832dda0
W=$(mktemp -d /build/k15/gen.XXXXXX)
trap 'rm -rf "$W"' EXIT
FILES="arch/x86/kernel/traps.c drivers/gpu/drm/i915/display/intel_display.c
drivers/gpu/drm/i915/display/intel_display_params.c drivers/gpu/drm/i915/display/intel_display_params.h"
export GIT_AUTHOR_NAME="GB-build k15" GIT_AUTHOR_EMAIL=k15@builder.invalid
export GIT_COMMITTER_NAME="GB-build k15" GIT_COMMITTER_EMAIL=k15@builder.invalid
D0="2026-10-26T12:00:00+00:00"
g() { git -C "$W/r" -c core.abbrev=12 "$@"; }
mkdir -p "$W/r" "$OUT/k15" "$OUT/repo"
g init -q
for f in $FILES; do mkdir -p "$W/r/$(dirname "$f")"; git -C "$SRC" show "$BASE:$f" > "$W/r/$f"; done
g add -A; GIT_AUTHOR_DATE=$D0 GIT_COMMITTER_DATE=$D0 g commit -q -m "P: android17-6.18 $BASE files"
for f in $FILES; do git -C "$SRC" show "k14-nouveau:$f" > "$W/r/$f"; done
g add -A; GIT_AUTHOR_DATE=$D0 GIT_COMMITTER_DATE=$D0 g commit -q -m "B: k14-nouveau files"
# the k14 tree differs from the base only by the v3 emulator in traps.c
[ "$(g diff --name-only HEAD~1 HEAD)" = arch/x86/kernel/traps.c ] || { echo "unexpected k14 vs base difference"; exit 1; }

python3 -I "$T/apply_vnni4.py" "$W/r/arch/x86/kernel/traps.c"
g add -A
GIT_AUTHOR_DATE="2026-10-26T12:00:00+00:00" GIT_COMMITTER_DATE="2026-10-26T12:00:00+00:00" g commit -q -F - <<'EOF'
x86/traps: VNNI emulator v4: IRQs on, xstate init state, MAXVL, counter

Kernel build #15 rework of the GB_VNNI_EMULATION #UD handler (k13/k14:
apply_vnni3.py). It emulates VEX-encoded AVX-VNNI (vpdpbusd, vpdpbusds,
vpdpwssd, vpdpwssds; VEX.128/256, register or memory source) for the
lapis userspace on Ice Lake, which has only the EVEX (AVX512_VNNI) forms.

Three defects of the k14 code are fixed:
 - The user copies ran with IRQs disabled (exc_invalid_op enters with
   them off), so a not-present page was faulted in from atomic context.
   handle_invalid_op() now brackets the emulator with
   cond_local_irq_enable()/cond_local_irq_disable(), the idiom of
   do_error_trap(). Every user access happens before kernel_fpu_begin().
 - SSE in its init state: the stale XMM buffer was read and the SSE bit
   set, which committed stale bytes into XMM0-15. The registers are now
   materialised as zeros first.
 - A VEX.128 destination kept bits 255:128, and no destination had bits
   511:256 zeroed (MAXVL, AVX-512 is enabled). The YMM and ZMM_Hi256
   components are written only when their header bit is set, and those
   bits are never set.
Hardening: insn_fetch_from_user() (an instruction that ends right before
an unmapped page is emulated); VEX.W1, no AVX, 32-bit code and uprobe
XOL slots are refused.

Decode, lanes and the xstate merge move to gb_vnni_core.h (pure C, unit
tested on the host by kernel/tools/test_gb_vnni_core.c).
/sys/kernel/gb_vnni/summary (0400) and reset (0200) count emulations
(vex128 vex256 word byte irqon efault sse_init ymm_init zmmhi) with a
16-entry comm/RIP LRU; a new bucket logs one rate-limited line. No new
export, no config change.

Generated by kernel/scripts/apply_vnni4.py.
IRQ/ymm/xstate review from github.com/linuxkid473/gbos-x86 @f8a5c1a
HANDOFF.md:59-62; code is ours.
EOF
python3 -I "$T/apply_i915_gamma.py" "$W/r"
g add -A
GIT_AUTHOR_DATE="2026-10-26T12:00:01+00:00" GIT_COMMITTER_DATE="2026-10-26T12:00:01+00:00" g commit -q -F - <<'EOF'
drm/i915/display: optional gb_ignore_user_gamma (default off)

Some panels show a grey "white veil" while userspace programs a gamma
LUT (Night Light, drm_hwcomposer without LOG_GAMMA_LUT support). Add the
display parameter i915.gb_ignore_user_gamma, a bitmask (1 = gamma LUT,
2 = degamma LUT, 4 = CTM). A set bit makes
intel_crtc_copy_uapi_to_hw_state_nomodeset() use NULL (linear) instead
of the user's blob; a joiner secondary copies the primary's hw state, so
it follows. The default 0 keeps the original expressions. The mode is
0400 because display params are copied at probe. 3 is the suggested
setting (CTM-based colour correction keeps working); 7 equals gbOS86
kernel #29.

Applicability to the Surface Book 3 panel is inferred, not confirmed;
nothing changes unless the module option is set.

Cause and fix from github.com/linuxkid473/gbos-x86 @f8a5c1a
HANDOFF.md:112-135; code is ours.
EOF

rm -f "$OUT"/k15/01*.patch
g format-patch -q --zero-commit --no-signature --start-number 110 -o "$W/fp" HEAD~2..HEAD
mv "$W/fp"/0110-*.patch "$OUT/k15/0110-x86-traps-vnni-emulator-irq-ymm-xsave-counter.patch"
mv "$W/fp"/0111-*.patch "$OUT/k15/0111-i915-optional-ignore-user-gamma.patch"
(cd "$OUT/k15" && sha256sum 0110-*.patch 0111-*.patch > SHA256SUMS)

P=$(g rev-parse HEAD~3); B=$(g rev-parse HEAD~2)
{ cat <<'EOF'
Subject: [PATCH] x86/traps: emulate VEX-encoded AVX-VNNI (#UD handler), v4

lapis userspace is built for CPUs with AVX-VNNI and executes vpdpbusd/vpdpbusds/vpdpwssd/vpdpwssds
unconditionally; Ice Lake (and the VMware guest, whose CPUID masks VNNI) raises #UD. handle_invalid_op() emulates
the VEX 0F38 50..53 forms (VEX.128/256, register and memory operands) for 64-bit user mode and skips the
instruction. Marker GB_VNNI_EMULATION. Generated by kernel/scripts/apply_vnni4.py (kernel build #15; the k13/k14
form was apply_vnni3.py, the first 128-bit register-only one apply_vnni_patch.py).
v4 (build #15): the user copies run with IRQs on (cond_local_irq_enable, as do_error_trap) and before
kernel_fpu_begin(); SSE/YMM/ZMM_Hi256 init state is honoured (a component is touched only when its XSTATE_BV bit
is set, YMM/ZMM_Hi256 bits are never set); VEX.128/256 zero the destination up to MAXVL; insn_fetch_from_user();
VEX.W1/no-AVX/uprobe-XOL refused; counter /sys/kernel/gb_vnni/{summary,reset}. Decode, lanes and the xstate merge
are in the new arch/x86/kernel/gb_vnni_core.h (host unit test: kernel/tools/test_gb_vnni_core.c).
Known gaps: lapis's libinput also uses VEX AVX-IFMA, which this does not emulate; legacy prefixes before VEX are
not emulated; a faulting memory operand gives SIGILL, not SIGSEGV; no debug trap after an emulated instruction
under single-step.
IRQ/ymm/xstate review from github.com/linuxkid473/gbos-x86 @f8a5c1a HANDOFF.md:59-62; code is ours.

Base: AOSP kernel/common android17-6.18-2026-06 at 3938c8d97142d5cf31543aa96f864a2cf832dda0 (kernel 6.18.21, ab/16302624;
     the full pin is kernel/manifest_16302624.xml). Apply in common/ with: git apply <this file>
License: GPL-2.0 (derived from Linux)
---
EOF
  g diff "$P" HEAD -- arch/x86/kernel; } > "$OUT/repo/0002-x86-traps-emulate-VEX-AVX-VNNI-for-the-Googlebook-userspace.patch"
{ cat <<'EOF'
Subject: [PATCH] drm/i915/display: optional gb_ignore_user_gamma (default off)

Display parameter i915.gb_ignore_user_gamma, a bitmask (1 = gamma LUT, 2 = degamma LUT, 4 = CTM, default 0, mode
0400): a set bit makes intel_crtc_copy_uapi_to_hw_state_nomodeset() use NULL (linear) instead of the user's blob, a
fix for the grey "white veil" some i915 panels show while userspace programs a gamma LUT. 3 is the suggested value
(CTM-based colour correction keeps working), 7 equals gbOS86 kernel #29. The value is fixed at module load; it is
set through the ESP bring-up config (GB_MODOPTS_i915=gb_ignore_user_gamma=3 in gb\gb.cfg, boot entry with
gb.overlay=1). Applicability to the Surface Book 3 panel is inferred; default off. Kernel build #15 (patch 0111 of
kernel/patches/k15 has the same hunks).
Cause and fix from github.com/linuxkid473/gbos-x86 @f8a5c1a HANDOFF.md:112-135; code is ours.

Base: AOSP kernel/common android17-6.18-2026-06 at 3938c8d97142d5cf31543aa96f864a2cf832dda0 (kernel 6.18.21, ab/16302624;
     the full pin is kernel/manifest_16302624.xml). Apply in common/ with: git apply <this file>
License: GPL-2.0 (derived from Linux)
---
EOF
  g diff "$P" HEAD -- drivers/gpu/drm/i915; } > "$OUT/repo/0005-i915-optional-ignore-user-gamma.patch"

# self-checks: 0111's i915 hunks == 0005's (k14's i915 files are the pristine ones)
[ "$(g diff "$B" HEAD -- drivers/gpu/drm/i915 | sha256sum)" = "$(g diff "$P" HEAD -- drivers/gpu/drm/i915 | sha256sum)" ] ||
  { echo "0111 != 0005 hunks"; exit 1; }
echo "0110: $(grep -c '^diff --git' "$OUT/k15/0110-"*.patch) files: $(grep '^diff --git' "$OUT/k15/0110-"*.patch | awk '{print substr($3,3)}' | tr '\n' ' ')"
echo "0111: $(grep -c '^diff --git' "$OUT/k15/0111-"*.patch) files, $(grep -c '^[-+][^-+]' "$OUT/k15/0111-"*.patch) changed lines"
echo "scratch commits: P=$(g rev-parse --short=12 "$P") B=$(g rev-parse --short=12 "$B") 0110=$(g rev-parse --short=12 HEAD~1) 0111=$(g rev-parse --short=12 HEAD)"
cat "$OUT/k15/SHA256SUMS"
sha256sum "$OUT"/repo/*.patch
