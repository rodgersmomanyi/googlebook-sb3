"""Build the per-library table (Markdown + CSV) from scan.json, dispatch_*.json and rip_matches.json.

Per VNNI function a dispatch class is assigned from its symbol name plus the dispatch analysis; per library the classes
are summed. Classes:
  ZLIB_SSSE3   Chromium-zlib adler32_simd_: adler32_z gates it on x86_cpu_enable_ssse3 (CPUID.1:ECX[9]) - passes on
               Ice Lake; the vpdpwssd is the compiler's fusion of pmaddwd+paddd under an AVX-VNNI -march.
  OLDER_ISA    function named for an older ISA (sse2/ssse3/sse4.1/avx/avx2/avx256skx, Sse*/Avx2*), selected at runtime by a
               cpuid-based table (libvpx/libaom rtcd, libgav1 GetCpuInfo, libyuv TestCpuFlag, XNNPACK/ruy cpuinfo, webrtc
               GetCPUInfo): the gate passes on Ice Lake, the VNNI inside comes from the same fusion.
  AVX512VNNI   XNNPACK *__avx256vnni*: selected when AVX512-VNNI(+VL) is reported (Ice Lake has it); the compiler used the
               VEX encoding because AVX-VNNI was also enabled.
  AVXVNNI_OK   XNNPACK *__avxvnni*: selected only when cpuinfo reports AVX-VNNI (CPUID.(7,1):EAX[4]) - never on Ice Lake.
  UNRESOLVED   stripped, no symbol and no fingerprint match (OpenVINO plugin); a CPUID(7,1) reader is present.
  ANON_XNN     stripped prebuilt: same instruction bytes as the named XNNPACK *__avxvnni* kernels and a CPUID(7,1) reader
               in the library (INFERRED AVXVNNI_OK).
  MLKEM        BoringSSL ML-KEM / Kyber (generic C), called unconditionally.
  PROTOBUF     protobuf generated ByteSizeLong / ExtensionSet::ByteSize (generic C++), virtual / unconditional.
  RUST_ZLIBRS  zlib-rs adler32 built with avx2 as a compile-time target feature (no runtime check in the function).
  COMPILE_TIME everything else: generic code auto-vectorised under the library-wide -march, no CPU check found.

usage: python -I report_tables.py EVIDENCE_DIR
"""
import collections, csv, json, os, re, sys

OLDER = re.compile(r"(?i)(?:__|_)(?:sse2|ssse3|sse4_?1|sse41|sse4|avx2|avx256skx|avx|fma3?|avx2_madd)(?:_|$|\.|\b)|"
                   r"(?:Sse|Avx2|Avx)(?:[A-Z]|Impl|Single)|_SSE2|_SSE41|_SSE4_1|_AVX2|_SSSE3")


def fclass(name):
    n = name or ""
    if "adler32_simd_" in n:
        return "ZLIB_SSSE3"
    if "zlib_rs" in n and "adler32" in n:
        return "RUST_ZLIBRS"
    if re.search(r"__avx256vnni", n):
        return "AVX512VNNI"
    if re.search(r"__avxvnni(?!int8)", n):
        return "AVXVNNI_OK"
    if re.search(r"mlkem|encrypt_cpa|decrypt_cpa|vector_compress|KYBER", n):
        return "MLKEM"
    if "ByteSize" in n:
        return "PROTOBUF"
    if OLDER.search(n):
        return "OLDER_ISA"
    return "COMPILE_TIME"


def short(p):
    p = p.replace("/var/tmp/vnniperf/", "")
    p = re.sub(r"^fs/system_b/", "/", p)
    p = re.sub(r"^fs/(vendor|product|system_ext)_b/", r"/\1/", p)
    p = re.sub(r"^apex/(system|vendor|system_ext|product)_b__", r"apex:", p)
    return p


def main():
    ev = sys.argv[1]
    scan = [r for r in json.load(open(os.path.join(ev, "scan.json"))) if r.get("hits")]
    disp = {}
    for n in ("dispatch_platform.json", "dispatch_apk.json"):
        for r in json.load(open(os.path.join(ev, n))):
            disp[r["path"]] = r
    rips = json.load(open(os.path.join(ev, "rip_matches.json")))
    seen_rt = collections.defaultdict(set)
    for m in rips:
        if m["comm"] == "vnni_kat":
            continue
        for f in m["full_matches"]:
            seen_rt[f["lib"]].add(m["comm"])
    named = set()
    for r in scan:
        for i in r["insns"]:
            if i["func"] and re.search(r"__avxvnni(?!int8)", i["func"]):
                named.add(i["bytes"])
    rows = []
    for r in scan:
        d = disp.get(r["path"], {})
        cls = collections.Counter()
        funcs = collections.Counter()
        anon = all(i["func"] is None for i in r["insns"])
        for i in r["insns"]:
            c = fclass(i["func"])
            if anon:
                share = sum(1 for j in r["insns"] if j["bytes"] in named) / len(r["insns"])
                l71 = any(c_.get("leaf7_sub1") for c_ in d.get("cpuid", []))
                c = "ANON_XNN" if share >= 0.4 and l71 else "UNRESOLVED"
            cls[c] += 1
            funcs[i["func"] or "(no symbol)"] += 1
        ops = collections.Counter("%s.%s" % (i["op"], "ymm" if i["L"] else "xmm") for i in r["insns"])
        cp = d.get("cpuid", [])
        rows.append(dict(
            lib=short(r["path"]), sha256=r["sha256"][:16], count=r["hits"], nfuncs=len(funcs),
            ops=" ".join("%s:%d" % kv for kv in sorted(ops.items())),
            classes=" ".join("%s:%d" % kv for kv in cls.most_common()),
            top=" ; ".join("%s(%d)" % (f[:70], n) for f, n in funcs.most_common(3)),
            cpuid="%d site(s)%s" % (len(cp), ", leaf7.1" if any(c_.get("leaf7_sub1") for c_ in cp) else "") if d else "-",
            bmi2=d.get("bmi2", ""), runtime=",".join(sorted(seen_rt.get(r["path"], ()))),
            vnniint8=len(r.get("other_vex_only", {}))))
    rows.sort(key=lambda x: (-x["count"], x["lib"]))
    with open(os.path.join(ev, "libs.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    with open(os.path.join(ev, "libs_table.md"), "w", encoding="utf-8") as f:
        f.write("| # | library | sha256[:16] | VEX VNNI | funcs | forms | dispatch classes (insns) | top functions | cpuid in lib | BMI2 lines | seen at runtime (comm) |\n")
        f.write("|---|---|---|---:|---:|---|---|---|---|---:|---|\n")
        for k, x in enumerate(rows, 1):
            f.write("| %d | `%s` | `%s` | %d | %d | %s | %s | %s | %s | %s | %s |\n" % (
                k, x["lib"], x["sha256"], x["count"], x["nfuncs"], x["ops"], x["classes"],
                x["top"].replace("|", "/").replace("_", "\\_"), x["cpuid"], x["bmi2"], x["runtime"] or ""))
    tot = collections.Counter()
    for x in rows:
        for kv in x["classes"].split():
            k, v = kv.rsplit(":", 1); tot[k] += int(v)
    libs = collections.Counter()
    for x in rows:
        for kv in x["classes"].split():
            libs[kv.rsplit(":", 1)[0]] += 1
    print("libraries", len(rows), "instructions", sum(x["count"] for x in rows))
    for k, v in tot.most_common():
        print("  %-14s insns %6d  libs %3d" % (k, v, libs[k]))


if __name__ == "__main__":
    main()
