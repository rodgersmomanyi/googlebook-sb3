#!/usr/bin/env python3
"""Generates gb_shim_tramp.inc for the GbGfxDriver shim from the Vulkan registry (vk.xml of the Mesa tree whose
headers the shim is compiled against).

For every Vulkan command whose first parameter is a VkPhysicalDevice (physical-device level) it emits a trampoline
that finds the driver owning that handle (ANV or NVK) and forwards the call; for every other command whose first
parameter is a VkInstance it emits a trampoline that swaps the shim instance for the base (ANV) instance. Commands the
shim implements itself (CUSTOM) are skipped. Platform commands are guarded by their protect macro, provisional ones by
VK_ENABLE_BETA_EXTENSIONS; commands only in Vulkan SC or in disabled extensions are left out.

Usage: python3 -I gen_trampolines.py <vk.xml> <out.inc>
"""
import sys
import xml.etree.ElementTree as ET

CUSTOM = {
    "vkCreateInstance", "vkDestroyInstance", "vkEnumeratePhysicalDevices", "vkEnumeratePhysicalDeviceGroups",
    "vkEnumeratePhysicalDeviceGroupsKHR", "vkGetInstanceProcAddr", "vkGetDeviceProcAddr", "vkCreateDevice",
    "vkEnumerateInstanceExtensionProperties", "vkEnumerateInstanceLayerProperties", "vkEnumerateInstanceVersion",
}


def api_ok(el):
    api = el.get("api")
    return api is None or "vulkan" in api.split(",")


def main():
    reg = ET.parse(sys.argv[1]).getroot()
    protect = {p.get("name"): p.get("protect") for p in reg.find("platforms")}

    # command -> guard ("" = unguarded); only commands required by a vulkan feature or a supported extension
    guard = {}
    for feat in reg.findall("feature"):
        if not api_ok(feat) or "vulkan" not in feat.get("api", "vulkan").split(","):
            continue
        for req in feat.findall("require"):
            if not api_ok(req):
                continue
            for c in req.findall("command"):
                guard[c.get("name")] = ""
    for ext in reg.find("extensions"):
        sup = ext.get("supported", "")
        if "vulkan" not in sup.split(","):
            continue
        g = ""
        if ext.get("platform"):
            g = protect[ext.get("platform")]
        elif ext.get("provisional") == "true":
            g = "VK_ENABLE_BETA_EXTENSIONS"
        for req in ext.findall("require"):
            if not api_ok(req):
                continue
            for c in req.findall("command"):
                n = c.get("name")
                if n not in guard or (guard[n] and not g):
                    guard[n] = g

    cmds = {}
    aliases = {}
    for c in reg.find("commands"):
        if not api_ok(c):
            continue
        if c.get("alias"):
            aliases[c.get("name")] = c.get("alias")
            continue
        proto = c.find("proto")
        name = proto.find("name").text
        ret = "".join(proto.itertext()).strip()
        ret = ret[: ret.rfind(name)].strip()
        params = []
        for p in c.findall("param"):
            if not api_ok(p):
                continue
            decl = " ".join("".join(p.itertext()).split())
            pname = p.find("name").text
            ptype = p.find("type").text
            params.append((decl, pname, ptype))
        cmds[name] = (ret, params)
    for a, t in aliases.items():
        if t in cmds:
            cmds[a] = cmds[t]

    pd, inst = [], []
    for name in sorted(cmds):
        if name not in guard or name in CUSTOM:
            continue
        ret, params = cmds[name]
        if not params:
            continue
        if params[0][2] == "VkPhysicalDevice":
            pd.append(name)
        elif params[0][2] == "VkInstance":
            inst.append(name)

    out = []
    w = out.append
    w("/* Generated by gen_trampolines.py from %s - do not edit. */" % sys.argv[1].split("/src/")[-1])
    w("/* %d physical-device-level and %d instance-level trampolines */" % (len(pd), len(inst)))
    w("")

    def guarded(name, lines):
        g = guard[name]
        if g:
            w("#ifdef %s" % g)
        for l in lines:
            w(l)
        if g:
            w("#endif")

    w("enum gb_pd_fn {")
    for n in pd:
        guarded(n, ["   GB_PD_%s," % n])
    w("   GB_PD_COUNT")
    w("};")
    w("enum gb_inst_fn {")
    for n in inst:
        guarded(n, ["   GB_INST_%s," % n])
    w("   GB_INST_COUNT")
    w("};")
    w("")
    w("static const char *const gb_pd_names[GB_PD_COUNT + 1] = {")
    for n in pd:
        guarded(n, ['   "%s",' % n])
    w("   NULL")
    w("};")
    w("static const char *const gb_inst_names[GB_INST_COUNT + 1] = {")
    for n in inst:
        guarded(n, ['   "%s",' % n])
    w("   NULL")
    w("};")
    w("")

    def default_ret(ret):
        if ret == "void":
            return "return;"
        if ret == "VkResult":
            return "return VK_ERROR_EXTENSION_NOT_PRESENT;"
        if ret.endswith("*"):
            return "return NULL;"
        return "return (%s)0;" % ret

    for kind, names in (("pd", pd), ("inst", inst)):
        for n in names:
            ret, params = cmds[n]
            decl = ", ".join(p[0] for p in params)
            first = params[0][1]
            if kind == "pd":
                args = ", ".join(p[1] for p in params)
                body = [
                    "static VKAPI_ATTR %s VKAPI_CALL gbt_%s(%s)" % (ret, n, decl),
                    "{",
                    "   PFN_%s f = (PFN_%s)gb_pd_lookup(%s, GB_PD_%s);" % (n, n, first, n),
                    "   if (f == NULL)",
                    "      %s" % default_ret(ret),
                    "   %sf(%s);" % ("" if ret == "void" else "return ", args),
                    "}",
                ]
            else:
                args = ", ".join(["base_instance"] + [p[1] for p in params[1:]])
                body = [
                    "static VKAPI_ATTR %s VKAPI_CALL gbt_%s(%s)" % (ret, n, decl),
                    "{",
                    "   VkInstance base_instance;",
                    "   PFN_%s f = (PFN_%s)gb_inst_lookup(%s, GB_INST_%s, &base_instance);" % (n, n, first, n),
                    "   if (f == NULL)",
                    "      %s" % default_ret(ret),
                    "   %sf(%s);" % ("" if ret == "void" else "return ", args),
                    "}",
                ]
            guarded(n, body)
    w("")
    w("static const struct gb_tramp_entry gb_tramp_table[] = {")
    for n in pd:
        guarded(n, ['   { "%s", GB_KIND_PD, GB_PD_%s, (PFN_vkVoidFunction)gbt_%s },' % (n, n, n)])
    for n in inst:
        guarded(n, ['   { "%s", GB_KIND_INST, GB_INST_%s, (PFN_vkVoidFunction)gbt_%s },' % (n, n, n)])
    w("   { NULL, 0, 0, NULL }")
    w("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print("gen_trampolines: %d physical-device-level, %d instance-level commands" % (len(pd), len(inst)))


if __name__ == "__main__":
    main()
