#!/usr/bin/env python3
"""Generate the Vulkan 1.0-1.3 core trampolines for libgb_nvk_loader.so (INTERFACES 11.2).

usage: python3 -I gen_trampolines.py <vulkan_core.h> <out.inc> [<names.txt>]

Parses the VK_VERSION_1_0 .. VK_VERSION_1_3 sections of vulkan_core.h (prototypes inside #ifndef VK_NO_PROTOTYPES) and
writes C code with:
  * struct gb_inst_fns / gb_dev_fns: one PFN per instance-level / device-level core command;
  * gb_fill_inst_fns() / gb_fill_dev_fns(): resolve them through the ICD's vk_icdGetInstanceProcAddr and the ICD's
    vkGetDeviceProcAddr;
  * one exported trampoline per core command that is not hand-written in libgb_nvk_loader.c (GB_HANDWRITTEN below).
    A trampoline reads the dispatch pointer that the stub stored in the first word of the dispatchable handle (the
    standard loader/ICD contract: ICDs put ICD_LOADER_MAGIC there and loaders overwrite it).
  * gb_core_names[]: every core command name (the self test dlsym()s each one).
The output is deterministic (source order of the header).
"""
import re
import sys

# Commands implemented by hand in libgb_nvk_loader.c (they create/destroy dispatchable objects or are global).
GB_HANDWRITTEN = {
    "vkCreateInstance", "vkDestroyInstance", "vkEnumeratePhysicalDevices", "vkGetInstanceProcAddr",
    "vkGetDeviceProcAddr", "vkCreateDevice", "vkDestroyDevice", "vkEnumerateInstanceExtensionProperties",
    "vkEnumerateInstanceLayerProperties", "vkEnumerateDeviceExtensionProperties", "vkEnumerateDeviceLayerProperties",
    "vkGetDeviceQueue", "vkAllocateCommandBuffers", "vkEnumerateInstanceVersion", "vkEnumeratePhysicalDeviceGroups",
    "vkGetDeviceQueue2",
}
INST_HANDLES = {"VkInstance", "VkPhysicalDevice"}
DEV_HANDLES = {"VkDevice", "VkQueue", "VkCommandBuffer"}
VERSIONS = ["VK_VERSION_1_0", "VK_VERSION_1_1", "VK_VERSION_1_2", "VK_VERSION_1_3"]

PROTO = re.compile(r"VKAPI_ATTR\s+(?P<ret>[\w\s\*]+?)\s+VKAPI_CALL\s+(?P<name>vk\w+)\s*\((?P<params>[^;]*?)\)\s*;", re.S)


def core_section(text):
    start = text.find("#define VK_VERSION_1_0 1")
    if start < 0:
        raise SystemExit("VK_VERSION_1_0 not found")
    end = text.find("#define VK_VERSION_1_4 1")
    if end < 0:
        end = text.find("#define VK_KHR_surface 1")
    if end < 0:
        raise SystemExit("end of the core section not found")
    sec = text[start:end]
    for v in VERSIONS:
        if "#define %s 1" % v not in sec:
            raise SystemExit("%s missing" % v)
    return sec


def protos(sec):
    out = []
    for blk in re.findall(r"#ifndef VK_NO_PROTOTYPES\n(.*?)#endif", sec, re.S):
        for m in PROTO.finditer(blk):
            ret = " ".join(m.group("ret").split())
            name = m.group("name")
            params = []
            raw = " ".join(m.group("params").split())
            if raw and raw != "void":
                for p in raw.split(","):
                    p = p.strip()
                    pm = re.match(r"^(?P<type>.*?)(?P<pname>\w+)\s*(?P<arr>\[\w+\])?$", p)
                    if not pm:
                        raise SystemExit("cannot parse parameter %r of %s" % (p, name))
                    params.append((p, pm.group("pname"), pm.group("type").strip()))
            out.append((ret, name, params))
    return out


def kind(params):
    if not params:
        return "global"
    t = params[0][2].replace("const", "").replace("*", "").strip()
    if t in INST_HANDLES:
        return "inst"
    if t in DEV_HANDLES:
        return "dev"
    return "global"


def default_ret(ret):
    if ret == "void":
        return "return;"
    if ret == "VkResult":
        return "return VK_ERROR_INITIALIZATION_FAILED;"
    return "return (%s)0;" % ret


def main():
    if len(sys.argv) not in (3, 4):
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as f:
        text = f.read()
    hv = re.search(r"#define VK_HEADER_VERSION (\d+)", text)
    ps = protos(core_section(text))
    names = [p[1] for p in ps]
    if len(set(names)) != len(names):
        raise SystemExit("duplicate prototypes")
    missing = sorted(GB_HANDWRITTEN - set(names))
    if missing:
        raise SystemExit("hand-written commands not in the header: %s" % missing)
    inst = [p for p in ps if kind(p[2]) == "inst"]
    dev = [p for p in ps if kind(p[2]) == "dev"]
    glob = [p for p in ps if kind(p[2]) == "global"]
    L = []
    w = L.append
    w("/* GENERATED by gen_trampolines.py from vulkan_core.h VK_HEADER_VERSION %s - do not edit. */" %
      (hv.group(1) if hv else "?"))
    w("/* %d core commands: %d instance-level, %d device-level, %d global; %d hand-written. */" %
      (len(ps), len(inst), len(dev), len(glob), len(GB_HANDWRITTEN)))
    w("")
    w("struct gb_inst_fns {")
    for _, n, _ in inst:
        w("    PFN_%s %s;" % (n, n[2:]))
    w("};")
    w("")
    w("struct gb_dev_fns {")
    for _, n, _ in dev:
        w("    PFN_%s %s;" % (n, n[2:]))
    w("};")
    w("")
    w("static void gb_fill_inst_fns(struct gb_inst_fns *f, VkInstance i, PFN_vkGetInstanceProcAddr gipa)")
    w("{")
    for _, n, _ in inst:
        w('    f->%s = (PFN_%s)gipa(i, "%s");' % (n[2:], n, n))
    w("}")
    w("")
    w("static void gb_fill_dev_fns(struct gb_dev_fns *f, VkDevice d, PFN_vkGetDeviceProcAddr gdpa)")
    w("{")
    for _, n, _ in dev:
        w('    f->%s = (PFN_%s)gdpa(d, "%s");' % (n[2:], n, n))
    w("}")
    w("")
    w("__attribute__((unused)) static const char *const gb_core_names[] = {")
    for n in names:
        w('    "%s",' % n)
    w("};")
    w("")
    for ret, n, params in ps:
        if n in GB_HANDWRITTEN:
            continue
        k = kind(params)
        if k == "global":
            raise SystemExit("unexpected global command %s (add it to GB_HANDWRITTEN)" % n)
        decl = ", ".join(p[0] for p in params)
        call = ", ".join(p[1] for p in params)
        h = params[0][1]
        getter = "gb_inst_fns_of" if k == "inst" else "gb_dev_fns_of"
        ftype = "gb_inst_fns" if k == "inst" else "gb_dev_fns"
        w("GB_EXPORT VKAPI_ATTR %s VKAPI_CALL %s(%s)" % (ret, n, decl))
        w("{")
        w("    const struct %s *f = %s(%s);" % (ftype, getter, h))
        w('    if (!f || !f->%s) { gb_missing("%s"); %s }' % (n[2:], n, default_ret(ret)))
        if ret == "void":
            w("    f->%s(%s);" % (n[2:], call))
        else:
            w("    return f->%s(%s);" % (n[2:], call))
        w("}")
        w("")
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    if len(sys.argv) == 4:
        with open(sys.argv[3], "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(names) + "\n")
    print("gen_trampolines: %d core commands (%d inst, %d dev, %d global), header %s" %
          (len(ps), len(inst), len(dev), len(glob), hv.group(1) if hv else "?"))


if __name__ == "__main__":
    main()
