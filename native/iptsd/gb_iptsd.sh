#!/system/bin/sh
# gb_iptsd.sh - Surface Book 3 touchscreen + Surface Pen for Googlebook native mode (gb.hw=native).
#
# The linux-surface ipts driver (ipts.ko, MEI client 3e8d0870-271a-4208-8eb5-9acb9402ae04 on PCI 8086:34E4) exposes
# the touch controller as a HID device named "IPTS VVVV:PPPP" (HID bus 0, group generic; vendor/product come from the
# touch firmware: Surface Book 3 13.5" = 045E:09B2, 15" = 045E:09B1). iptsd turns its heatmaps and pen reports into
# two uinput devices, "IPTSD Virtual Touchscreen VVVV:PPPP" and "IPTSD Virtual Stylus VVVV:PPPP" (BUS_VIRTUAL).
# Android has no udev, so this launcher:
#   1. waits for the IPTS device's hidraw node (sysfs HID_NAME "IPTS *"; after 10 s it also asks iptsd-check-device
#      about every hidraw node),
#   2. writes Android IDC files into /odm/usr/idc (searched before /vendor/usr/idc) for the kernel's own fallback
#      single-touch input device(s) of that HID device, and for iptsd's uinput devices when no IDC exists for them
#      yet (the Surface Book 3 ones ship statically in /vendor/usr/idc),
#   3. runs iptsd on the node and restarts it when it exits, when the node goes away and after every resume
#      (/sys/power/suspend_stats/success changes: the touch firmware can fall back to single-touch mode),
#   4. reloads ipts.ko when the device vanished and does not come back (the known IPTS resume bug,
#      "Failed to set memory window") or iptsd failed right away 5 times in a row; at most 3 reloads in a row.
# A user config at /data/vendor/iptsd/iptsd.conf replaces /odm/etc/iptsd/iptsd.conf (+ iptsd.d/) when present.
# Knobs: setprop persist.gb.iptsd.disable 1 (do not run), persist.gb.iptsd.reload 0 (never reload ipts.ko).
# Log: stdout goes to the kernel log (rc: stdio_to_kmsg) -> dmesg | grep -i iptsd
# The GB_IPTSD_* environment overrides exist only for testing this script off-device.

BIN=${GB_IPTSD_BIN:-/vendor/bin/iptsd}
CHECK=${GB_IPTSD_CHECK:-/vendor/bin/iptsd-check-device}
SYS=${GB_IPTSD_SYS:-/sys}
DEVDIR=${GB_IPTSD_DEVDIR:-/dev}
IDC=${GB_IPTSD_IDC:-/odm/usr/idc}
STATIC_IDC=${GB_IPTSD_STATIC_IDC:-/vendor/usr/idc}
KO=${GB_IPTSD_KO:-/odm/lib/modules/ipts.ko}
USERCONF=${GB_IPTSD_USERCONF:-/data/vendor/iptsd/iptsd.conf}
POLL=${GB_IPTSD_POLL:-2}
SUSP=${GB_IPTSD_SUSPEND_STATS:-$SYS/power/suspend_stats/success}

log() { echo "gb_iptsd: $*"; }
prop() { getprop "$1" 2>/dev/null; }
uptime_s() { read -r _u _ < /proc/uptime; echo "${_u%%.*}"; }
suspend_count() { _s=; read -r _s < "$SUSP" 2>/dev/null; echo "$_s"; }

# Android's IDC lookup name for an input device: every char except [A-Za-z0-9_-] becomes '_'.
canon() { echo "${1//[!A-Za-z0-9_-]/_}"; }

# idc NAME KIND COMMENT: make sure Android finds an IDC for input device NAME (KIND touch|stylus|kernel).
idc() {
	_c=$(canon "$1")
	[ -e "$STATIC_IDC/$_c.idc" ] && return 0
	[ -e "$IDC/$_c.idc" ] && return 0
	mkdir -p "$IDC" || return 1
	{
		echo "# Generated by gb_iptsd.sh: $3"
		echo "device.internal = 1"
		echo "touch.deviceType = touchScreen"
		echo "touch.orientationAware = 1"
		# iptsd reports ABS_MT_ORIENTATION as 0..180 degrees, not the symmetric range Android interpolates.
		[ "$2" = touch ] && echo "touch.orientation.calibration = none"
	} > "$IDC/$_c.idc"
	chmod 0644 "$IDC/$_c.idc"
	log "wrote $IDC/$_c.idc ($1)"
}

# find_node: prints "hidrawN VVVV:PPPP" for the first hidraw node whose HID device is named "IPTS VVVV:PPPP".
find_node() {
	for _u in "$SYS"/class/hidraw/hidraw*/device/uevent; do
		[ -r "$_u" ] || continue
		_n=
		while IFS== read -r _k _v; do
			[ "$_k" = HID_NAME ] && _n=$_v
		done < "$_u"
		case "$_n" in
		"IPTS "????:????)
			_h=${_u%/device/uevent}
			echo "${_h##*/} ${_n#IPTS }"
			return 0;;
		esac
	done
	return 1
}

# find_node_check: same, but any hidraw node that iptsd-check-device accepts (VVVV:PPPP from HID_ID).
find_node_check() {
	[ -x "$CHECK" ] || return 1
	for _d in "$DEVDIR"/hidraw*; do
		[ -c "$_d" ] || continue
		"$CHECK" --quiet "$_d" > /dev/null 2>&1 || continue
		_h=${_d##*/}; _i=
		while IFS== read -r _k _v; do
			[ "$_k" = HID_ID ] && _i=$_v
		done < "$SYS/class/hidraw/$_h/device/uevent"
		_p=${_i##*:}; _i=${_i#*:}; _i=${_i%%:*}       # HID_ID=BBBB:VVVVVVVV:PPPPPPPP
		echo "$_h ${_i#????}:${_p#????}"
		return 0
	done
	return 1
}

reload_ipts() {
	log "$1: reloading the ipts driver"
	rmmod ipts 2>&1
	sleep 1
	insmod "$KO" 2>&1 || log "insmod $KO failed"
}

if [ "$(prop persist.gb.iptsd.disable)" = 1 ]; then
	log "disabled (persist.gb.iptsd.disable=1)"
	exit 0
fi
if [ ! -x "$BIN" ]; then
	log "$BIN missing"
	exit 1
fi
[ -r "$SUSP" ] || { log "no $SUSP: no restart after resume"; SUSP=/dev/null; }
_w=0
while [ ! -c "$DEVDIR/uinput" ] && [ $_w -lt 30 ]; do sleep 1; _w=$((_w + 1)); done
[ -c "$DEVDIR/uinput" ] || log "warning: $DEVDIR/uinput missing, iptsd will fail"

seen=0      # the IPTS device was found at least once during this run
reloads=0   # ipts.ko reloads since iptsd last ran fine
fast=0      # iptsd runs in a row that ended within 10 s
while :; do
	# 1. wait for the IPTS hidraw device
	waited=0; next_check=10; nap=$POLL
	while :; do
		node=$(find_node) && break
		if [ $waited -ge $next_check ]; then
			node=$(find_node_check) && break
			next_check=$((waited + 30))
		fi
		if [ $seen = 1 ] && [ $waited -ge 15 ] && [ $reloads -lt 3 ] && [ "$(prop persist.gb.iptsd.reload)" != 0 ]; then
			reload_ipts "IPTS device gone and not coming back"
			reloads=$((reloads + 1)); waited=0; next_check=10
			continue
		fi
		[ $waited = 0 ] && log "waiting for the IPTS hidraw device (ipts.ko loaded? MEI 8086:34E4 bound?)"
		[ $waited -ge 60 ] && nap=5
		sleep $nap; waited=$((waited + nap))
		[ $((waited % 300)) -lt $nap ] && log "still no IPTS device after ${waited}s"
	done
	set -- $node
	h=$1; vp=$2
	_w=0
	while [ ! -c "$DEVDIR/$h" ] && [ $_w -lt 20 ]; do sleep 0.5; _w=$((_w + 1)); done
	if [ ! -c "$DEVDIR/$h" ]; then
		log "$DEVDIR/$h does not exist (ueventd?)"
		sleep $POLL
		continue
	fi
	seen=1

	# 2. IDC files: the kernel's input devices of the IPTS HID device (hid-generic single-touch fallback, silent
	#    while iptsd keeps the firmware in multitouch mode) and iptsd's two uinput devices.
	for _f in "$SYS"/class/hidraw/$h/device/input/input*/name; do
		[ -r "$_f" ] || continue
		read -r _n < "$_f"
		[ -n "$_n" ] && idc "$_n" kernel "kernel ipts HID input device (single-touch fallback without iptsd)"
	done
	idc "IPTSD Virtual Touchscreen $vp" touch "iptsd multitouch touchscreen"
	idc "IPTSD Virtual Stylus $vp" stylus "iptsd stylus (Surface Pen: pen, eraser, pressure, tilt)"

	# 3. run iptsd until it exits, the node disappears or the system resumes from suspend
	if [ -r "$USERCONF" ]; then
		export IPTSD_CONFIG_FILE="$USERCONF"
		log "using $USERCONF"
	else
		unset IPTSD_CONFIG_FILE
	fi
	log "starting $BIN $DEVDIR/$h (IPTS $vp)"
	t0=$(uptime_s)
	susp=$(suspend_count)
	"$BIN" "$DEVDIR/$h" &
	pid=$!
	why=exit
	while kill -0 $pid 2> /dev/null; do
		sleep $POLL
		if [ ! -e "$SYS/class/hidraw/$h" ]; then why=device-gone; break; fi
		_s=; read -r _s < "$SUSP"
		if [ "$_s" != "$susp" ]; then why=resume; break; fi
	done
	if kill -0 $pid 2> /dev/null; then
		kill $pid 2> /dev/null
		_w=0
		while kill -0 $pid 2> /dev/null && [ $_w -lt 10 ]; do sleep 0.3; _w=$((_w + 1)); done
		kill -9 $pid 2> /dev/null
	fi
	wait $pid
	rc=$?
	ran=$(($(uptime_s) - t0))
	log "iptsd stopped: $why, rc=$rc after ${ran}s"

	# 4. back off when iptsd keeps failing right away
	if [ $why = exit ] && [ $ran -lt 10 ]; then
		fast=$((fast + 1))
		if [ $fast -ge 5 ] && [ $reloads -lt 3 ] && [ "$(prop persist.gb.iptsd.reload)" != 0 ]; then
			reload_ipts "iptsd failed $fast times in a row"
			reloads=$((reloads + 1)); fast=0
			sleep 2
			continue
		fi
		_d=$((fast * 2)); [ $_d -gt 30 ] && _d=30
		sleep $_d
	else
		[ $ran -ge 10 ] && reloads=0
		fast=0
		sleep 1
	fi
done
